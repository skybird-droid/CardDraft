let gameStarted = false;

const rarityChances = {
    common: 60,
    rare: 25,
    epic: 10,
    legendary: 5
};

function getRandomCards(array, count) {
    const pool = [...array];
    const selected = [];

    while (selected.length < count && pool.length > 0) {
        const totalWeight = pool.reduce((sum, card) => {
            return sum + (rarityChances[card.rarity] || 1);
        }, 0);

        let random = Math.random() * totalWeight;
        let index = 0;

        for (; index < pool.length; index++) {
            const weight = rarityChances[pool[index].rarity] || 1;
            random -= weight;
            if (random < 0) break;
        }

        if (index >= pool.length) {
            index = pool.length - 1;
        }

        selected.push(pool.splice(index, 1)[0]);
    }

    return selected;
}

function showCards(side) {

    if (gameStarted) return;

    gameStarted = true;

    const container = document.getElementById("cardContainer");
    container.innerHTML = "";

    const selectedCards =
        side === "light"
            ? getRandomCards(lightSideCards, 4)
            : getRandomCards(darkSideCards, 4);

    selectedCards.forEach(cardData => {

        const card = document.createElement("div");
        card.classList.add("card", "face-down");

        const img = document.createElement("img");
        img.src = cardData.image;
        img.style.display = "none";

        card.appendChild(img);

        card.addEventListener("click", () => {

            if (card.classList.contains("revealed")) return;

            card.classList.add("revealed");
            card.classList.add(cardData.rarity);
            card.classList.remove("face-down");

            img.style.display = "block";

            const name = document.createElement("div");
            name.classList.add("character-name");
            name.textContent = cardData.name;

            card.appendChild(name);
        });

        container.appendChild(card);
    });

    document.querySelector(".button-container").style.display = "none";
}